export class QuoteBannerController {
  constructor(containerId = 'dietQuoteBanner') {
    this.container = document.getElementById(containerId);
    this.quoteTextEl = document.getElementById('quoteText');
    this.quoteAuthorEl = document.getElementById('quoteAuthor');
    this.currentIndex = 0;
    this.timer = null;
    this.autoRotateInterval = 9000; // 9초마다 자동 회전
    this.init();
  }

  init() {
    if (!this.container) return;
    this.currentIndex = Math.floor(Math.random() * DIET_QUOTES.length);
    this.render();
    this.bindEvents();
    this.startAutoRotate();
  }

  render() {
    if (!this.quoteTextEl) return;
    const item = DIET_QUOTES[this.currentIndex] || DIET_QUOTES[0];

    this.quoteTextEl.style.opacity = '0';
    this.quoteTextEl.style.transform = 'translateY(5px)';
    if (this.quoteAuthorEl) {
      this.quoteAuthorEl.style.opacity = '0';
    }

    setTimeout(() => {
      this.quoteTextEl.textContent = `"${item.quote}"`;
      if (this.quoteAuthorEl) {
        this.quoteAuthorEl.textContent = `— ${item.author}`;
      }
      this.quoteTextEl.style.opacity = '1';
      this.quoteTextEl.style.transform = 'translateY(0)';
      if (this.quoteAuthorEl) {
        this.quoteAuthorEl.style.opacity = '1';
      }
    }, 180);
  }

  next() {
    this.currentIndex = (this.currentIndex + 1) % DIET_QUOTES.length;
    this.render();
    this.restartAutoRotate();
  }

  prev() {
    this.currentIndex = (this.currentIndex - 1 + DIET_QUOTES.length) % DIET_QUOTES.length;
    this.render();
    this.restartAutoRotate();
  }

  random() {
    let nextIdx;
    do {
      nextIdx = Math.floor(Math.random() * DIET_QUOTES.length);
    } while (nextIdx === this.currentIndex && DIET_QUOTES.length > 1);
    this.currentIndex = nextIdx;
    this.render();
    this.restartAutoRotate();
  }

  startAutoRotate() {
    this.stopAutoRotate();
    this.timer = setInterval(() => {
      this.next();
    }, this.autoRotateInterval);
  }

  stopAutoRotate() {
    if (this.timer) {
      clearInterval(this.timer);
      this.timer = null;
    }
  }

  restartAutoRotate() {
    this.startAutoRotate();
  }

  bindEvents() {
    document.getElementById('btnNextQuote')?.addEventListener('click', () => this.next());
    document.getElementById('btnPrevQuote')?.addEventListener('click', () => this.prev());
    document.getElementById('btnRandomQuote')?.addEventListener('click', () => this.random());

    this.container.addEventListener('mouseenter', () => this.stopAutoRotate());
    this.container.addEventListener('mouseleave', () => this.startAutoRotate());
  }
}
